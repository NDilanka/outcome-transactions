"""Exports the gate and rule-test results into research/exp6-executed/results/ (committed evidence).

Reads gate/result_mutants.json (from gate_check.py) and gate/rule_test.json (from rule_test.py), both gitignored
because they hold copies of the roots. Writes decisions without paths: gate_decisions.json, gate_table.md, and
rule_test.md. Run after gate_mutants.py, gate_check.py, and rule_test.py.
"""
import collections, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'results')


def first_nonpass(rec):
    for p in rec['predicates']:
        if p['status'] != 'PASS':
            return f"{p['status']}: {p['pred'][:80]}".replace('|', '/').replace('\n', ' ')
    return ''


def main():
    os.makedirs(OUT, exist_ok=True)
    gate = json.load(open(os.path.join(HERE, 'gate', 'result_mutants.json')))
    rules = json.load(open(os.path.join(HERE, 'gate', 'rule_test.json')))

    decisions = [{'task': r['task'][:8], 'state': r['state'], 'kind': r['kind'], 'executor': r['decision'],
                  'osworld': r['official'],
                  'non_pass': [{'status': p['status'], 'pred': p['pred']} for p in r['predicates'] if p['status'] != 'PASS']}
                 for r in gate]
    json.dump(decisions, open(os.path.join(OUT, 'gate_decisions.json'), 'w'), indent=1, ensure_ascii=False)

    counts = collections.Counter((r['kind'], r['decision']) for r in gate)
    lines = ['# Gate decisions (generated by results_export.py)', '',
             'Roots: 12 starts, 21 known-correct (17 OSWorld gold, 4 my positives), 40 mutants.', '',
             '| kind | executor decision | count |', '|---|---|---|']
    for (k, d), n in sorted(counts.items()):
        lines.append(f'| {k} | {d} | {n} |')
    lines += ['', '| task | state | kind | executor | OSWorld | first non-pass predicate |', '|---|---|---|---|---|---|']
    for r in gate:
        lines.append(f"| {r['task'][:8]} | {r['state']} | {r['kind']} | {r['decision']} | {r['official']} | {first_nonpass(r)} |")
    open(os.path.join(OUT, 'gate_table.md'), 'w').write('\n'.join(lines) + '\n')

    lines = ['# Counterfactual rule test (generated by results_export.py)', '',
             'Hand-applied edits to copies of the exp5 must lists. The specs are unchanged. Each row is one root.',
             'A row where the original is REJECT and the variant is ACCEPT or UNDECIDED on a mutant is a regression.', '',
             '| task | variant | cause | state | kind | original | variant | change |', '|---|---|---|---|---|---|---|---|']
    for r in rules:
        change = '' if r['original'] == r['variant_decision'] else f"{r['original']} -> {r['variant_decision']}"
        lines.append(f"| {r['task']} | {r['variant']} | {r['cause']} | {r['state']} | {r['kind']} | {r['original']} | "
                     f"{r['variant_decision']} | {change} |")
    open(os.path.join(OUT, 'rule_test.md'), 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
